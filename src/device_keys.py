"""Per-device HMAC key lookup.

Normal deployments need nothing here: devices enroll themselves and are approved with one
click (registry.py, ADR 0006), and their keys live in the device registry.

Lookup order for a device's key:
  1. environment variable ``DEVICE_KEY_<DEVICE_ID>``            (legacy v0 firmware)
  2. JSON key file at ``AEGIS_DEVICE_KEYS_FILE`` or ``<data dir>/device_keys.json`` (legacy)
  3. the device registry (zero-touch enrolled, protocol v1)

A device with no key is *unknown*: its frames are rejected and no command can
be signed for it. There is deliberately no shared fallback key.

The ``generate`` CLI below is only needed for legacy v0 firmware with compiled-in keys::

    python src/device_keys.py generate ESP32_001 --out device_keys.json --firmware-header aegis_secrets.h

Both output files are git-ignored.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import secrets
import sys
from typing import Dict, Optional

DEVICE_ID_PATTERN = re.compile(r"^[A-Za-z0-9_\-]{1,50}$")
MIN_KEY_LENGTH = 16

_file_cache: Dict[str, object] = {"path": None, "mtime": None, "keys": {}}


def is_valid_device_id(device_id: object) -> bool:
    return isinstance(device_id, str) and bool(DEVICE_ID_PATTERN.match(device_id))


def default_keys_file() -> str:
    explicit = os.environ.get("AEGIS_DEVICE_KEYS_FILE")
    if explicit:
        return explicit
    try:
        from database import DATABASE_URL

        if DATABASE_URL.startswith("sqlite:///"):
            return os.path.join(
                os.path.dirname(DATABASE_URL[len("sqlite:///") :]), "device_keys.json"
            )
    except Exception:
        pass
    return os.path.join(os.getcwd(), "device_keys.json")


def _load_file_keys() -> Dict[str, str]:
    path = default_keys_file()
    try:
        mtime = os.path.getmtime(path)
    except OSError:
        return {}
    if _file_cache["path"] == path and _file_cache["mtime"] == mtime:
        return _file_cache["keys"]  # type: ignore[return-value]
    try:
        with open(path, "r", encoding="utf-8") as fh:
            raw = json.load(fh)
        keys = {k: v for k, v in raw.items() if is_valid_device_id(k) and isinstance(v, str)}
    except (OSError, ValueError) as exc:
        print(f"[DeviceKeys] Could not read key file {path}: {exc}")
        keys = {}
    _file_cache.update(path=path, mtime=mtime, keys=keys)
    return keys


def get_device_key(device_id: str) -> Optional[str]:
    """Return the HMAC key for ``device_id`` or ``None`` if the device is not provisioned."""
    if not is_valid_device_id(device_id):
        return None
    key = os.environ.get(f"DEVICE_KEY_{device_id}") or _load_file_keys().get(device_id)
    if not key:
        key = _registry_key(device_id)
    if key and len(key) >= MIN_KEY_LENGTH:
        return key
    if key:
        print(
            f"[DeviceKeys] Ignoring key for {device_id}: shorter than {MIN_KEY_LENGTH} characters."
        )
    return None


def _registry_key(device_id: str) -> Optional[str]:
    """Key of a device enrolled through the registry (zero-touch enrollment, ADR 0006)."""
    try:
        import registry

        return registry.get_key(device_id)
    except Exception:
        return None


def provisioned_devices() -> set:
    """Devices with a usable key: legacy env/file provisioning plus registry-approved devices."""
    ids = {k[len("DEVICE_KEY_") :] for k in os.environ if k.startswith("DEVICE_KEY_")}
    ids |= set(_load_file_keys())
    try:
        import registry

        ids |= set(registry.approved_device_ids())
    except Exception:
        pass
    return {d for d in ids if get_device_key(d)}


def warn_about_missing_keys(expected=()) -> None:
    """Kept for compatibility; devices now enroll themselves, so nothing is required up front."""
    missing = [d for d in expected if not get_device_key(d)]
    if missing:
        print(
            "[DeviceKeys] No key yet for: "
            + ", ".join(missing)
            + " (approve them on the dashboard)."
        )


# ------------------------------------------------------------------- CLI ---


def _firmware_header(keys: Dict[str, str]) -> str:
    lines = [
        "// Generated by src/device_keys.py -- DO NOT COMMIT (git-ignored).",
        "#pragma once",
        "",
    ]
    for dev, key in sorted(keys.items()):
        lines.append(f'#define AEGIS_KEY_{dev} "{key}"')
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Aegis ICS device key tool")
    sub = parser.add_subparsers(dest="cmd", required=True)
    gen = sub.add_parser("generate", help="generate random per-device HMAC keys")
    gen.add_argument("devices", nargs="+")
    gen.add_argument("--out", default="device_keys.json")
    gen.add_argument("--firmware-header", default=None)
    gen.add_argument("--force", action="store_true", help="overwrite existing keys")
    args = parser.parse_args(argv)

    bad = [d for d in args.devices if not is_valid_device_id(d)]
    if bad:
        parser.error(f"invalid device id(s): {bad}")

    existing: Dict[str, str] = {}
    if os.path.exists(args.out):
        with open(args.out, "r", encoding="utf-8") as fh:
            existing = json.load(fh)
    for dev in args.devices:
        if dev in existing and not args.force:
            print(f"keeping existing key for {dev} (use --force to rotate)")
            continue
        existing[dev] = secrets.token_hex(32)

    fd = os.open(args.out, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        json.dump(existing, fh, indent=2, sort_keys=True)
    print(f"wrote {len(existing)} key(s) to {args.out}")

    if args.firmware_header:
        with open(args.firmware_header, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(_firmware_header(existing))
        print(f"wrote firmware header {args.firmware_header}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
